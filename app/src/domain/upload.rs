use std::marker::PhantomData;

use bytes::Bytes;

use super::encoding::AsPlainRef;
use super::name::Name;
use super::record::{Content, Existing};
use super::{
	Brief, Brotli, Entry, Error, Plain, Record, RecordStored, Result, Slug,
};
use crate::domain::{Checksum, ContentPacked, ContentPlain};

pub struct Upload<S, E> {
	content: Content<E>, // becomes Brotli when becoming a Record
	slug:    Option<Slug>,
	state:   S,
}

// possible [S]tates during the upload process
struct Pending(Option<Checksum>); // payload received but not yet approved against the DB
// In order to be approved, the checksum has to be computed. Carying it through
// state ensures that, although cheap, it doesn't get computed twice.
struct Hashed(Option<Checksum>);
struct Approved(Option<Checksum>); // content is approved but no slug (confirmed to be unique) generated

pub type UploadPending = Upload<Pending, Plain>;
pub type UploadApproved = Upload<Approved, Plain>;
pub type UploadPacked = Upload<Approved, Brotli>;

impl UploadPending {
	pub fn try_redirect(bytes: Vec<u8>, slug: Option<Box<str>>) -> Result<Self> {
		let slug = match slug {
			None => None,
			Some(s) => Some(Slug::parse(s)?),
		};
		Ok(Self {
			content: ContentPlain::redirect(Bytes::from(bytes)),
			slug,
			state: Pending(None),
		})
	}

	pub fn paste(bytes: Bytes) -> Self {
		let checksum = Some(Checksum::of(&bytes));
		Self {
			content: ContentPlain::paste(bytes),
			slug:    None, // always autogenerated
			state:   Pending(checksum),
		}
	}

	pub fn checksum(&self) -> Option<Checksum> { self.state.0 }

	/// Checksums are a quick pre-check but don't prevent collisions.
	/// `resolve` verifies that the uncompressed bytes match for
	/// records with colliding checksums.
	pub fn resolve(
		self,
		partial_collisions: Vec<RecordStored>,
	) -> Result<Resolved> {
		// only check duplicates for pastes
		// multiple redirects can point to the same destination
		if let Content::Paste(blob) = &self.content {
			let bytes = blob.bytes.as_plain_ref()?;

			for record in partial_collisions {
				let Entry::Served(Content::Paste(existing)) = &record.entry else {
					continue;
				};

				if existing.matches(bytes.as_ref())? {
					let (Existing(created), slug) = (record.created, record.slug);
					return Ok(Resolved::Existing(Brief {
						slug,
						kind: super::RouteKind::Paste,
						created,
					}));
				}
			}
		}

		Ok(Resolved::Novel(Upload {
			content: self.content,
			slug:    self.slug,
			state:   Approved(self.state.0),
		}))
	}
}

impl UploadApproved {
	pub fn prepare(self) -> Result<UploadReady> {
		Ok(UploadReady {
			name:     self.slug.into(),
			content:  self.content.compress()?,
			checksum: self.state.0,
		})
	}
}

// Wether data can be returned from existing storage
// or is approved for insertion
pub enum Resolved {
	Existing(Brief),
	Novel(UploadApproved),
}

pub struct UploadReady {
	name:     Name,
	content:  ContentPacked,
	checksum: Option<Checksum>,
}
