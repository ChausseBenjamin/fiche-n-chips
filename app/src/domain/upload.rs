use std::marker::PhantomData;

use bytes::Bytes;

use super::record::Existing;
use super::{Blob, Content, Error, Meta, Plain, Record, Result, Slug};
use crate::domain::Brotli;
use crate::domain::encoding::AsPlainRef;

pub enum UploadData {
	Paste(Blob<Plain>),
	Redir(Plain),
}

// possible [S]tates during the upload process
struct Pending; // payload received but not yet approved against the DB
struct Approved; // uploading the payload is approved (slug not check yet)
pub struct Upload<S> {
	content: UploadData, // becomes Brotli when becoming a Record
	slug:    Option<Slug>,
	state:   PhantomData<S>,
}
impl Upload<Pending> {
	pub fn try_redirect(bytes: Vec<u8>, slug: Option<String>) -> Result<Self> {
		let slug = match slug {
			None => None,
			Some(s) => Some(Slug::try_from(s)?),
		};
		Ok(Self {
			content: UploadData::Redir(Plain(Bytes::from(bytes))),
			slug,
			state: PhantomData,
		})
	}

	pub fn paste(bytes: Vec<u8>) -> Self {
		Self {
			content: Blob::new(bytes),
			slug:    None, // always autogenerated
			state:   PhantomData,
		}
	}

	/// Checksums are a quick pre-check but don't prevent collisions.
	/// `resolve` verifies that the uncompressed bytes match for
	/// records with colliding checksums.
	pub fn resolve(
		self,
		partial_collisions: Vec<Record<Existing, Brotli>>,
	) -> Result<Resolved> {
		// only check duplicates for pastes
		// multiple redirects can point to the same destination
		if let UploadData::Paste(blob) = &self.content {
			let bytes = blob.bytes.as_plain_ref()?;

			for record in partial_collisions {
				let Content::Paste(existing) = &record.entry else {
					continue;
				};

				if existing.matches(bytes.as_ref())? {
					let (Existing(created), slug) = (record.created, record.slug);
					return Ok(Resolved::Existing(Meta { slug, created }));
				}
			}
		}

		Ok(Resolved::Novel(Upload {
			content: self.content,
			slug:    self.slug,
			state:   PhantomData,
		}))
	}
}

pub enum Resolved {
	Existing(Meta),
	Novel(Upload<Approved>),
}
