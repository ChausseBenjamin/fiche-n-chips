use std::time::SystemTime;

use structx::*;
use xxhash_rust::xxh3::{xxh3_64, xxh3_64_with_seed};

use super::Route;

/// Representation where the content remains compressed
pub struct CompPaste {
	pub(super) slug: String,
	pub(super) hash: u64, // format used by xxh3
	pub(super) content: Vec<u8>,
	pub(super) created: SystemTime,
}

impl From<CompPaste> for Route {
	fn from(value: CompPaste) -> Self {
		Route::Paste(value)
	}
}

pub struct MatchingPaste {
	pub slug: String,
	pub content: Vec<u8>,
}

/// Representation where the content hasn't ben compressed
/// Hash can be derived from uncompressed contents so it isn't stored.
pub struct RawPaste {
	slug: String, // Autogenerated path for the pasted data (aka ID)
	content: String,
	created: SystemTime,
}

/// Every received paste starts off as a String
/// and each will be need to be hashed for both:
/// - check against the DB for matching files
/// - insertion in the DB
pub struct HashedPaste(HashedPasteInner);

struct HashedPasteInner {
	content: String,
	hash: u64,
}

impl HashedPaste {
	pub fn hash(&self) -> u64 {
		self.0.hash
	}
	// TODO: maybe pass a ref to that string to avoid cloning?
	pub fn content(&self) -> String {
		self.0.content
	}
}

impl From<String> for HashedPaste {
	fn from(value: String) -> Self {
		Self(HashedPasteInner {
			content: value,
			hash: xxh3_64_with_seed(value.as_bytes(), 0),
		})
	}
}
